// Shot-list exports generated entirely in the browser. "PDF" opens a print-ready page; choose "Save as PDF".
type A = any;
const COLUMNS: [string, string][] = [["shot", "Shot"], ["duration_s", "Duration (s)"], ["purpose", "Narrative purpose"], ["size", "Shot size"], ["angle", "Angle"],
  ["camera_position", "Camera position"], ["lens", "Lens"], ["movement", "Movement"], ["focus_dof", "Focus / depth of field"], ["blocking", "Blocking"],
  ["lighting", "Lighting"], ["lighting_detail", "Lighting detail"], ["equipment", "Equipment"], ["continuity", "Continuity"], ["transition", "Transition"], ["notes", "Notes"]];

function cell(v: A) {
  let s = Array.isArray(v) ? v.join("; ") : v === null || v === undefined ? "" : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = "'" + s;      // neutralise spreadsheet formulas
  return /[",\n\r]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}

export function shotlistCsv(d: A) {
  const lines = [COLUMNS.map(([, l]) => cell(l)).join(","), ...d.rows.map((r: A) => COLUMNS.map(([k]) => cell(r[k])).join(","))];
  return "﻿" + lines.join("\r\n") + "\r\n";
}

export function shotlistJson(d: A, project: string) {
  return JSON.stringify({ format: "cinevision.shotlist/1", edition: "browser", exported_at: new Date().toISOString(), project, shot_list: d }, null, 2);
}

const esc = (s: A) => String(s ?? "").replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;");

/** Renders the shot list into a hidden iframe and opens the browser's print dialog (Save as PDF). */
export function printShotlist(d: A, project: string) {
  const rows = d.rows.map((r: A) => `<tr><td>${r.shot}<br><small>${r.duration_s}s</small></td><td>${esc(r.purpose)}</td><td>${esc(r.size)}<br><small>${esc(r.angle)}</small></td>
    <td>${esc(r.camera_position)}<br>${esc(r.lens)}</td><td>${esc(r.movement)}</td><td>${esc(r.focus_dof)}</td><td>${esc(r.blocking)}</td>
    <td>${esc(r.lighting)}<ul>${r.lighting_detail.map((x: string) => `<li>${esc(x)}</li>`).join("")}</ul></td><td>${esc(r.equipment.join(", "))}</td><td>${esc(r.transition)}</td></tr>`).join("");
  const endings = (d.alternative_endings || []).map((e: A) => `<li><b>${esc(e.name)}</b> (${esc(e.size)}, ${esc(e.movement)}): ${esc(e.note)}</li>`).join("");
  const html = `<!doctype html><html><head><meta charset="utf-8"><title>${esc(project)} — shot list</title><style>
    @page { size: A4 landscape; margin: 10mm } body { font: 9pt/1.35 -apple-system, "Segoe UI", Roboto, sans-serif; color: #111 }
    h1 { font-size: 16pt; margin: 0 0 2mm } p { margin: 0 0 2mm } table { width: 100%; border-collapse: collapse; table-layout: fixed }
    th { background: #2b313a; color: #fff; text-align: left; padding: 3px } td { border: 0.5pt solid #b9b2a5; padding: 3px; vertical-align: top; word-wrap: break-word }
    tr:nth-child(even) td { background: #f3efe7 } ul { margin: 2px 0 0; padding-left: 12px } small { color: #555 } .sw span { display: inline-block; width: 18px; height: 10px }
  </style></head><body>
    <h1>${esc(project)} — ${esc(d.concept_name)}</h1>
    <p>Shot list · ${esc(d.aspect_ratio)} · ${esc(d.frame_rate)} fps · ${esc(d.total_duration_s)} s · revision ${esc(d.concept_revision ?? 1)}</p>
    <p>Grade: ${esc(d.grade)} <span class="sw">${d.palette.map((c: string) => `<span style="background:${esc(c)}"></span>`).join("")}</span></p>
    <table><thead><tr><th style="width:4%">#</th><th>Purpose</th><th>Frame</th><th>Camera &amp; lens</th><th>Movement</th><th>Focus</th><th>Blocking</th><th style="width:17%">Lighting</th><th>Kit</th><th>Next</th></tr></thead>
    <tbody>${rows}</tbody></table>
    ${endings ? `<h3>Alternative endings</h3><ul>${endings}</ul>` : ""}
    <p style="margin-top:4mm"><i>Generated by CineVision Studio (browser edition) from a proxy previsualisation. Positions, distances and lighting are planning estimates — verify on set.</i></p>
  </body></html>`;
  const f = document.createElement("iframe");
  f.style.cssText = "position:fixed;right:0;bottom:0;width:0;height:0;border:0";
  f.setAttribute("aria-hidden", "true");
  document.body.appendChild(f);
  const doc = f.contentDocument!;
  doc.open(); doc.write(html); doc.close();
  setTimeout(() => { f.contentWindow?.focus(); f.contentWindow?.print(); setTimeout(() => f.remove(), 60000); }, 250);
}
